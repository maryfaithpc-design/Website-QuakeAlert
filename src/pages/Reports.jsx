import { useEffect, useState } from "react";

function Reports() {
  const [sensor, setSensor] = useState(null);
  const [history, setHistory] = useState([]);

  const userId =
    localStorage.getItem("quakealertUserId");

  // Get the current sensor data and saved history
  useEffect(() => {
    if (!userId) {
      return;
    }

    fetch(
      `http://localhost:5000/api/sensor?userId=${userId}`
    )
      .then((response) => response.json())
      .then((data) => {
        setSensor(data);
      })
      .catch((error) => {
        console.error(
          "Sensor error:",
          error
        );
      });

    fetch(
      `http://localhost:5000/api/history?userId=${userId}`
    )
      .then((response) => response.json())
      .then((data) => {
        setHistory(data);
      })
      .catch((error) => {
        console.error(
          "History error:",
          error
        );
      });
  }, [userId]);

  // Report periods are based on today's date
  const today = new Date();

  const monthStart = new Date(
    today.getFullYear(),
    today.getMonth(),
    1
  );

  const weekStart = new Date(today);
  weekStart.setDate(today.getDate() - 6);
  weekStart.setHours(0, 0, 0, 0);

  function formatDay(date) {
    return date.toLocaleDateString(
      "en-US",
      {
        month: "long",
        day: "numeric"
      }
    );
  }

  const monthName = today.toLocaleDateString(
    "en-US",
    {
      month: "long"
    }
  );

  const reports = [
    {
      title: `${monthName} ${today.getFullYear()} Monitoring Report`,
      period: `${formatDay(monthStart)} - ${formatDay(today)}, ${today.getFullYear()}`,
      start: monthStart
    },
    {
      title: "Weekly Vibration Report",
      period: `${formatDay(weekStart)} - ${formatDay(today)}, ${today.getFullYear()}`,
      start: weekStart
    }
  ].map((report) => {
    // Only include readings from this report's period
    const readings = history.filter(
      (reading) =>
        new Date(reading.timestamp) >=
        report.start
    );

    return {
      ...report,
      readings,
      alerts: readings.filter(
        (reading) =>
          reading.status !== "NORMAL"
      )
    };
  });

  // Download a monitoring report
  function downloadReport(report) {
    if (!sensor) {
      return;
    }

    const historyText =
      report.readings.length === 0
        ? "No vibration events recorded."
        : report.readings
            .map(
              (reading, index) =>
                `${index + 1}. ${new Date(
                  reading.timestamp
                ).toLocaleString()} | Vibration: ${
                  reading.vibration
                } | Status: ${
                  reading.status
                }`
            )
            .join("\n");

    const text = `
QUAKEALERT MONITORING REPORT

Report: ${report.title}
Monitoring Period: ${report.period}

DEVICE INFORMATION

Device ID: ${sensor.deviceId}
Location: ${sensor.location}
Sensor: ${sensor.sensor}
Protocol: MQTT

CURRENT STATUS

Current Vibration: ${sensor.vibration}
Current Status: ${sensor.status}
Last Update: ${new Date(
      sensor.timestamp
    ).toLocaleString()}

ALERT SUMMARY

Total Recorded Events: ${report.readings.length}
Warning and Critical Events: ${report.alerts.length}

VIBRATION EVENT HISTORY

${historyText}

SUMMARY

System: QuakeAlert
Monitoring Type: Real-Time

This report contains vibration monitoring
information generated by the QuakeAlert system.

The vibration thresholds used by this prototype are:

0–2 Normal
2–5 Warning
5+ Critical

These prototype thresholds are for system
demonstration and are not official earthquake
safety measurements.
`;

    const file = new Blob(
      [text],
      {
        type: "text/plain"
      }
    );

    const url =
      URL.createObjectURL(file);

    const link =
      document.createElement("a");

    link.href = url;

    link.download =
      `${report.title.replaceAll(
        " ",
        "_"
      )}.txt`;

    link.click();

    URL.revokeObjectURL(url);
  }

  return (
    <div className="reports-page">

      <h1>
        Reports
      </h1>

      <p>
        View and download your vibration
        monitoring reports.
      </p>

      {reports.map((report) => (

        <div
          className="report-card"
          key={report.title}
        >

          <div>

            <h2>
              {report.title}
            </h2>

            <p>
              {sensor
                ? `${sensor.deviceId} • ${sensor.location}`
                : "Loading..."}
            </p>

            <p>
              Monitoring Period:
              {" "}
              {report.period}
            </p>

            <p>
              Recorded Events:{" "}
              {report.readings.length}
            </p>

            <p>
              Alerts:{" "}
              {report.alerts.length}
            </p>

          </div>

          <button
            onClick={() =>
              downloadReport(report)
            }
          >
            Download Report
          </button>

        </div>

      ))}

    </div>
  );
}

export default Reports;